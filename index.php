        <div class="plate-faq-accordion">
          <div class="faq-plate-item active">
            <button class="faq-plate-btn">What is the difference between Porcelain, Bone China, and Stoneware? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-plate-content">
              Porcelain is fired at 1,280&deg;C&ndash;1,300&deg;C from pure kaolin clay and feldspar, achieving zero water absorption (&lt; 0.05%) and supreme hardness. Bone China incorporates bone ash (tricalcium phosphate) to create warm ivory translucency and extraordinary chip-resistance in thin profiles. Stoneware is fired from iron-rich clay at 1,200&deg;C&ndash;1,240&deg;C, producing heavier, opaque, earthy pieces with tactile textural warmth.
            </div>
          </div>
          <div class="faq-plate-item">
            <button class="faq-plate-btn">How are high-fire ceramic plates tested for food safety and glaze leaching? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-plate-content">
              All TableAndPlate ceramic glazes are 100% free of toxic lead, cadmium, and barium. Tested according to FDA and California Proposition 65 standards, plates are submerged in 4% acetic acid for 24 hours to verify zero chemical leaching, ensuring complete safety even when serving highly acidic citrus reductions and culinary berry vinegars.
            </div>
          </div>
          <div class="faq-plate-item">
            <button class="faq-plate-btn">What causes thermal shock and micro-crazing in restaurant dinnerware? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-plate-content">
              Thermal shock occurs when a ceramic plate experiences rapid temperature changes (such as moving from a 70&deg;C hot holding salamander into a cold wash cycle). If the thermal expansion coefficient of the glaze does not match the underlying clay body, microscopic hairline cracks (crazing) form. Our ceramics are formulated with matched expansion coefficients to withstand thermal deltas of up to 240&deg;C without crazing.
            </div>
          </div>
          <div class="faq-plate-item">
            <button class="faq-plate-btn">Why do Michelin-starred chefs prefer coupe plates over traditional rimmed plates? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-plate-content">
              Coupe plates feature a continuous, rimless curved surface that maximizes usable culinary canvas space. This allows chefs to arrange asymmetrical, modern culinary compositions and sweep delicate emulsion sauces across the plate without being constrained by an artificial raised border rim.
            </div>
          </div>
        </div>
